// Generate Day 1 to Day 20 Historical Attendance Logs
export const generateInitialDailyLogs = (schoolId: string = 'SCH-01'): DailyLog[] => {
  const studentIds = DEFAULT_STUDENTS.map(s => s.id);
  const logs: DailyLog[] = [];

  for (let day = 1; day <= 20; day++) {
    const attendance: Record<string, 'present' | 'absent' | 'late'> = {};
    
    studentIds.forEach((id, idx) => {
      // Deterministic, realistic attendance patterns:
      // Most students present, occasional late or absent
      if (day === 4 && idx === 1) attendance[id] = 'absent';
      else if (day === 8 && idx === 5) attendance[id] = 'absent';
      else if (day === 12 && idx === 9) attendance[id] = 'late';
      else if (day === 15 && idx === 15) attendance[id] = 'absent';
      else if (day === 18 && idx === 17) attendance[id] = 'late';
      else if (day === 20 && idx === 3) attendance[id] = 'absent';
      else attendance[id] = 'present';
    });

    
    logs.push({
      id: `LOG-${schoolId}-D${day}`,
      schoolId,
      date: new Date(Date.now() - (20 - day) * 86400000).toISOString().split('T')[0],
      dayNumber: day,
      facultyId: 'USR-FAC-01',
      facultyName: 'Dr. Anjali Patil',
      moduleNumber: Math.min(6, Math.ceil(day / 3.5)),
      moduleTitle: `Module ${Math.min(6, Math.ceil(day / 3.5))}: Soil Science & Diagnostics`,
      topicsCovered: ['Daily Hands-On Testing & Calibration Protocols'],
      sessionType: day % 2 === 0 ? 'Practical' : 'Theory',
      hoursTaught: 2.5,
      plannedHours: 2.5,
      isDelayed: false,
      status: 'On_Time',
      studentAttendance: attendance,
      samplesTestedCount: 8 + (day % 5),
      farmersReachedCount: 12 + (day % 7),
      campaignsCount: Math.floor(day / 6),
      stockUsed: '10 filter papers, 80ml extractant',
      photos: ['/assets/images/module-soil-testing.png'],
      isLocked: day < 18, // Older than 48 hours are verified/locked
      submittedAt: new Date(Date.now() - (20 - day) * 86400000).toISOString()
    });
  }

  return logs;
};
